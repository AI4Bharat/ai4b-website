      ' seconds generated by ' + HERO.voice + '. ' +
      (need('capabilities') ? '<a href="#capabilities">Hear it below</a>.'
                            : '<a href="indic-speak.html#capabilities">Hear it</a>.');

    var canvas = document.createElement('canvas');
    canvas.className = 'wave-gl';
    canvas.setAttribute('aria-hidden', 'true');
    var gl = canvas.getContext('webgl2', { antialias: true, alpha: true, premultipliedAlpha: false });
